"""Direct ports: the only way a core service other than the edge publishes a host port.

The base compose files publish no port besides the edge proxy (`security/published-ports.yaml`
lists the one loopback exception, the API of Nginx Proxy Manager, and the link gateway of a
distributed installation). Reaching a service on a port of its own is a development mode,
chosen with `REVERSE_PROXY_PROVIDER=no_proxy` or with `setup --allow-direct-port-access`
(the bundled proxy then stays off). Only in that mode does `setup` write
`overrides/docker-compose.direct-ports.override.yml`, which publishes the ports of the
active core services; in every other mode it removes the file.

The file is generated, never edited: its first lines carry a digest of the body, and
`doctor` reports a file whose body no longer matches the digest, or no longer matches what
`setup` would write, as `fail`.

Some services never get a port, in no mode and on no address, `127.0.0.1` included
(betrieb BE-06, RE-21):

- a service that takes a person's identity from a request header (`header_identity: true`
  on an `exposes` entry; the service is the entry's `address.service`),
- `me-web`,
- every service of a module that declares `delegation` on an `exposes` entry.

`setup` and `doctor` refuse direct port access while such a service is part of the
installation, and refuse a `ports:` entry of such a service in any mode.
"""

from __future__ import annotations

import hashlib
import re
from dataclasses import dataclass
from pathlib import Path

import yaml

from . import common, deployment

OVERRIDE = Path("overrides") / "docker-compose.direct-ports.override.yml"
ME_WEB = "me-web"

NO_PROXY = "no_proxy"
ALLOW_FLAG = "--allow-direct-port-access"


@dataclass(frozen=True)
class DirectPort:
    """One core service's port in direct mode: its profile, the host port variable with
    the documented default, the container port and the default bind address."""

    profile: str
    service: str
    variable: str
    default: int
    target: int
    bind_default: str = "0.0.0.0"

    def entry(self) -> str:
        return (
            f"${{HOST_IP:-{self.bind_default}}}:${{{self.variable}:-{self.default}}}:{self.target}"
        )


# The ports the core services published before they moved behind the edge, with their
# documented defaults (src/.env.example). The NPM admin UI is not here: direct port access
# switches the bundled proxy off, and with it its admin UI.
CORE_DIRECT_PORTS: tuple[DirectPort, ...] = (
    DirectPort("keycloak", "keycloak", "KEYCLOAK_EXT_PORT", 8110, 8443),
    DirectPort("oauth2-proxy", "oauth2-proxy", "OAUTH2_PROXY_EXT_PORT", 4180, 4180),
    DirectPort("manager", "papaia-manager", "MANAGER_EXT_PORT", 8120, 8000),
    DirectPort("librechat", "librechat", "LIBRECHAT_EXT_PORT", 8000, 3080),
    DirectPort("litellm", "litellm", "LITELLM_EXT_PORT", 8200, 4000),
    DirectPort("localai", "localai", "LOCALAI_EXT_PORT", 8080, 8080),
    DirectPort("rag", "qdrant", "QDRANT_EXT_PORT", 6333, 6333, "127.0.0.1"),
    DirectPort("rag", "qdrant-ingest", "QDRANT_INGEST_EXT_PORT", 8300, 8300, "127.0.0.1"),
)

_HEADER = (
    "# Generated by papaia-ctl setup for direct port access ({mode}). Do not edit:\n"
    "# setup rewrites this file and doctor reports a changed one.\n"
)
_DIGEST_PREFIX = "# digest: sha256:"
_DIGEST_RE = re.compile(r"^# digest: sha256:([0-9a-f]{64})$")


class DirectPortsError(ValueError):
    """Direct port access that must not happen."""


@dataclass(frozen=True)
class Protected:
    """A service that never publishes a port, with the module and the reason."""

    module: str
    service: str
    reason: str

    def describe(self) -> str:
        return f"'{self.service}' of '{self.module}' ({self.reason})"


# ─────────────────────────────────────────────────────────────────────────
# mode
# ─────────────────────────────────────────────────────────────────────────


def _profiles(root: dict[str, str]) -> list[str]:
    return [p.strip() for p in (root.get("COMPOSE_PROFILES") or "").split(",") if p.strip()]


def direct_mode(root: dict[str, str]) -> str | None:
    """Why the installation described by the root `.env` reaches its services on ports:
    `no_proxy`, `--allow-direct-port-access` (the bundled proxy chosen but switched off),
    or None when the edge serves them."""
    provider = (root.get("REVERSE_PROXY_PROVIDER") or "").strip()
    if provider == NO_PROXY:
        return NO_PROXY
    # setup always stores the provider; without it nothing is published directly.
    if provider == "internal_nginx" and "nginx" not in _profiles(root):
        return ALLOW_FLAG
    return None


# ─────────────────────────────────────────────────────────────────────────
# protected services
# ─────────────────────────────────────────────────────────────────────────


class _ComposeLoader(yaml.SafeLoader):
    """safe_load plus the merge tags of Compose (`!reset`, `!override`), read as their
    plain values: a `ports: !override [...]` still publishes those ports."""


def _compose_tag(loader: yaml.SafeLoader, suffix: str, node: yaml.Node):
    if isinstance(node, yaml.MappingNode):
        return loader.construct_mapping(node, deep=True)
    if isinstance(node, yaml.SequenceNode):
        return loader.construct_sequence(node, deep=True)
    return loader.construct_scalar(node)


_ComposeLoader.add_multi_constructor("!reset", _compose_tag)
_ComposeLoader.add_multi_constructor("!override", _compose_tag)


def _compose_services(addon_path: Path) -> dict[str, dict]:
    return _compose_file_services(addon_path / "docker-compose.yml")


def _compose_file_services(path: Path) -> dict[str, dict]:
    if not path.is_file():
        return {}
    try:
        doc = yaml.load(path.read_text(encoding="utf-8"), Loader=_ComposeLoader) or {}
    except yaml.YAMLError as exc:
        raise DirectPortsError(f"{path} is not valid YAML: {exc}") from exc
    services = doc.get("services") if isinstance(doc, dict) else None
    if not isinstance(services, dict):
        return {}
    return {str(k): v if isinstance(v, dict) else {} for k, v in services.items()}


def _header_identity(entry: dict, where: str) -> bool:
    """The marker, read strictly: missing is False, anything but a boolean is refused,
    so a malformed manifest cannot open a port."""
    if "header_identity" not in entry:
        return False
    value = entry["header_identity"]
    if not isinstance(value, bool):
        raise DirectPortsError(f"{where}: header_identity must be true or false")
    return value


def _ingress_services(manifest: dict) -> dict[str, str]:
    """host_key -> service of the add-on's `integration.nginx` list (generation 12)."""
    nginx = (manifest.get("integration") or {}).get("nginx")
    if not isinstance(nginx, list):
        return {}
    return {
        str(e["host_key"]): str(e["service"])
        for e in nginx
        if isinstance(e, dict) and e.get("host_key") and e.get("service")
    }


def _identity_services(entry: dict, manifest: dict, services: dict[str, dict]) -> list[str]:
    """The services behind a marked entry: `address.service`, else the services of its
    `ui[].host_key` in `integration.nginx`. When neither names one, every service of the
    module counts: a marker that cannot be placed protects the whole module."""
    address = entry.get("address")
    if isinstance(address, dict) and isinstance(address.get("service"), str):
        return [address["service"]]
    by_key = _ingress_services(manifest)
    named = [
        by_key[item["host_key"]]
        for item in entry.get("ui") or []
        if isinstance(item, dict) and item.get("host_key") in by_key
    ]
    return named or sorted(services)


def protected_of(name: str, manifest: dict, services: dict[str, dict]) -> list[Protected]:
    """The services of one module that never publish a port."""
    found: dict[str, Protected] = {}
    exposes = manifest.get("exposes") or []
    if not isinstance(exposes, list):
        raise DirectPortsError(f"add-on '{name}': exposes must be a list")
    delegation = False
    for index, entry in enumerate(exposes):
        if not isinstance(entry, dict):
            raise DirectPortsError(f"add-on '{name}': exposes/{index} must be a mapping")
        where = f"add-on '{name}': exposes/{index}"
        if "delegation" in entry:
            delegation = True
        if _header_identity(entry, where):
            for service in _identity_services(entry, manifest, services):
                found.setdefault(service, Protected(name, service, "header identity"))
    for service in services:
        if service == ME_WEB:
            found.setdefault(service, Protected(name, service, "me-web"))
        elif delegation:
            found.setdefault(service, Protected(name, service, "module with delegation"))
    return sorted(found.values(), key=lambda p: (p.module, p.service))


def protected_services(config_dir: Path, repo_root: Path) -> list[Protected]:
    """Every service of the active add-ons that never publishes a port.
    DirectPortsError for a manifest that cannot be read."""
    found: list[Protected] = []
    for addon in deployment.active_addons(deployment.load(config_dir)):
        name = str(addon.get("name") or "?")
        path = deployment.resolve_addon_path(addon, repo_root)
        manifest, reason = deployment.load_addon_manifest(path)
        if manifest is None:
            raise DirectPortsError(f"add-on '{name}': {reason}")
        found.extend(protected_of(name, manifest, _compose_services(path)))
    return found


def published_by_addons(config_dir: Path, repo_root: Path) -> dict[tuple[str, str], list[str]]:
    """(add-on, service) -> its `ports:` entries, from the add-ons' own compose files and
    from their files in overrides/addons/, which `addon start` applies as well. Every
    entry counts, also one an override would `!reset`: fail closed."""
    deployed = deployment.load(config_dir)
    published: dict[tuple[str, str], list[str]] = {}
    for addon in deployment.active_addons(deployed):
        name = str(addon.get("name") or "?")
        path = deployment.resolve_addon_path(addon, repo_root)
        files = [path / "docker-compose.yml"]
        files += deployment.addon_override_files(config_dir, name, deployed)
        for file in files:
            for service, body in _compose_file_services(file).items():
                ports = body.get("ports")
                if not ports:
                    continue
                entries = [str(p) for p in ports] if isinstance(ports, list) else [str(ports)]
                known = published.setdefault((name, service), [])
                known.extend(e for e in entries if e not in known)
    return published


def refusals(root: dict[str, str], config_dir: Path, repo_root: Path) -> list[str]:
    """Why `setup` and `doctor` refuse: a protected service in direct mode, or a protected
    service that publishes a port in any mode. Empty when nothing is refused."""
    try:
        protected = protected_services(config_dir, repo_root)
        published = published_by_addons(config_dir, repo_root)
    except DirectPortsError as exc:
        return [str(exc)]
    messages = []
    mode = direct_mode(root)
    if mode and protected:
        names = ", ".join(p.describe() for p in protected)
        messages.append(
            f"direct port access ({mode}) is not allowed while the installation has a"
            f" service that never publishes a port: {names}. Use the edge proxy"
            " (--reverse-proxy-provider=internal_nginx or external_proxy, without"
            f" {ALLOW_FLAG})"
        )
    for item in protected:
        ports = published.get((item.module, item.service))
        if ports:
            messages.append(
                f"{item.describe()} publishes {', '.join(ports)}; it never publishes a port,"
                " also not on 127.0.0.1"
            )
    return messages


# ─────────────────────────────────────────────────────────────────────────
# the override
# ─────────────────────────────────────────────────────────────────────────


def render_body(root: dict[str, str]) -> str:
    """The compose body of the override for the active profiles (no header)."""
    profiles = set(_profiles(root))
    services = {
        port.service: {"ports": [port.entry()]}
        for port in CORE_DIRECT_PORTS
        if port.profile in profiles
    }
    return yaml.safe_dump({"services": services}, sort_keys=False, default_flow_style=False)


def _digest(body: str) -> str:
    return hashlib.sha256(body.encode("utf-8")).hexdigest()


def render(root: dict[str, str]) -> str | None:
    """The whole override file, or None when the installation is not in direct mode."""
    mode = direct_mode(root)
    if mode is None:
        return None
    body = render_body(root)
    return _HEADER.format(mode=mode) + f"{_DIGEST_PREFIX}{_digest(body)}\n" + body


def write(config_dir: Path, root: dict[str, str]) -> Path | None:
    """Write the override in direct mode, remove it otherwise. Returns the written path."""
    path = config_dir / OVERRIDE
    text = render(root)
    if text is None:
        path.unlink(missing_ok=True)
        return None
    path.parent.mkdir(parents=True, exist_ok=True)
    common.atomic_write(path, text)
    return path


def _split(text: str) -> tuple[str | None, str]:
    """(digest from the header or None, body after the header)."""
    lines = text.splitlines(keepends=True)
    digest = None
    index = 0
    while index < len(lines) and lines[index].startswith("#"):
        match = _DIGEST_RE.match(lines[index].rstrip("\n"))
        if match:
            digest = match.group(1)
        index += 1
    return digest, "".join(lines[index:])


def missing(config_dir: Path, root: dict[str, str]) -> bool:
    """Direct port access without its override: the services are not reachable, which is
    no exposure (doctor warns)."""
    return direct_mode(root) is not None and not (config_dir / OVERRIDE).is_file()


def verify(config_dir: Path, root: dict[str, str]) -> list[str]:
    """Findings about the override on disk: present without direct mode, missing in
    direct mode, edited by hand (digest), or out of date with the configuration."""
    path = config_dir / OVERRIDE
    mode = direct_mode(root)
    if not path.is_file():
        if mode:
            return [f"{OVERRIDE} is missing for direct port access ({mode}); run setup again"]
        return []
    if mode is None:
        return [
            f"{OVERRIDE} publishes ports although the edge proxy serves the installation;"
            " run setup again to remove it"
        ]
    try:
        text = path.read_text(encoding="utf-8")
    except OSError as exc:
        return [f"{OVERRIDE} cannot be read: {exc.strerror or exc}"]
    digest, body = _split(text)
    if digest is None or digest != _digest(body):
        return [f"{OVERRIDE} was edited by hand; it is generated, run setup again"]
    if text != render(root):
        return [f"{OVERRIDE} does not match the configuration; run setup again"]
    return []
