"""Every pinned image of the core, resolved against a registry (tools/check-image-pins).

The start check (lib/images.py) compares the images Compose is about to run with the
signed bill of materials. It cannot notice a pin that no registry serves: a digest that
was built on one machine and never pushed, or a tag that was moved to another build
after the pin was taken. This check reads every pin of the checkout

- `services.*.image` and every `x-papaia-*-images` value of the compose files under
  `src/`,
- the `image` of every `service-env.json` under `src/` (the env list of a module image,
  lib/me_profile.py),
- every image of the bill of materials of the checkout's suite
  (`compat/suite-<suite>.yaml`, when there is one),

and asks the registry for each one: the digest must exist, and the tag must point to
exactly that digest. Each problem names the file and line of the pin.

Two modes:

- `release`: every pin is resolved at the registry it names. A pin that names a loopback
  registry fails, so no test registry name can stay in a release. With `--own-builds`
  (the builds file of tools/build-images) the core's own images, which the tag run
  publishes, are resolved in the registry of that build instead; their digests must be
  the built ones.
- `candidate`: each pin is resolved first behind `--registry` (a local test registry,
  `<host:port>/<path>/` on the loopback interface, as `PAPAIA_IMAGE_MIRROR` names it),
  then at the registry it names. It refuses to run on a release tag.

The check only reads registries (pull access, with the host's Docker credentials when
there are any); it needs no push credential and writes nothing.

`repin` moves the pins of one image to a new tag and digest in every compose file and
`service-env.json` at once (the bill of materials is signed and is regenerated by the
release, never edited). Run `check` again afterwards.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

import yaml

from . import images, own_images

MODES = ("release", "candidate")
SERVICE_ENV_NAME = "service-env.json"
MAX_PINS = 512
MAX_FILE_BYTES = 1024 * 1024

_RELEASE_TAG_RE = re.compile(r"\Av\d+\.\d+\.\d+")


class PinError(ValueError):
    """An input or a setting the check refuses; the message says why."""


@dataclass(frozen=True)
class Pin:
    path: str  # relative to the checkout, POSIX
    line: int  # 1-based
    where: str  # the field, e.g. services.me-web.image
    ref: str

    @property
    def location(self) -> str:
        return f"{self.path}:{self.line}"


@dataclass(frozen=True)
class Finding:
    pin: Pin
    reason: str

    def __str__(self) -> str:
        return f"{self.pin.location}: {self.pin.where}: {self.pin.ref}: {self.reason}"


# ── collecting the pins ──────────────────────────────────────────────────────


def _read(path: Path) -> str:
    if path.is_symlink() or not path.is_file():
        raise PinError(f"{path}: not a regular file")
    if path.stat().st_size > MAX_FILE_BYTES:
        raise PinError(f"{path}: larger than {MAX_FILE_BYTES} bytes")
    return path.read_text(encoding="utf-8")


def _rel(root: Path, path: Path) -> str:
    return path.relative_to(root).as_posix()


def _mapping_items(node) -> list:
    return node.value if isinstance(node, yaml.MappingNode) else []


def _compose_pins(root: Path, path: Path) -> list[Pin]:
    text = _read(path)
    try:
        node = yaml.compose(text)
    except yaml.YAMLError as exc:
        raise PinError(f"{_rel(root, path)}: not YAML ({type(exc).__name__})") from exc
    rel = _rel(root, path)
    found: list[Pin] = []
    for key, value in _mapping_items(node):
        if key.value == "services":
            for service, body in _mapping_items(value):
                for field, image in _mapping_items(body):
                    if field.value == "image":
                        found.append(_scalar_pin(rel, f"services.{service.value}.image", image))
        elif isinstance(key.value, str) and key.value.startswith("x-papaia-") and (
            key.value.endswith("-images")
        ):
            for variant, image in _mapping_items(value):
                found.append(_scalar_pin(rel, f"{key.value}.{variant.value}", image))
    return found


def _scalar_pin(rel: str, where: str, node) -> Pin:
    if not isinstance(node, yaml.ScalarNode) or not isinstance(node.value, str):
        raise PinError(f"{rel}:{node.start_mark.line + 1}: {where} must be one image reference")
    return Pin(rel, node.start_mark.line + 1, where, node.value)


def _service_env_pins(root: Path, path: Path) -> list[Pin]:
    text = _read(path)
    rel = _rel(root, path)
    try:
        doc = json.loads(text)
    except ValueError as exc:
        raise PinError(f"{rel}: not JSON") from exc
    if not isinstance(doc, dict) or "image" not in doc:
        return []
    ref = doc["image"]
    if not isinstance(ref, str):
        raise PinError(f"{rel}: image must be one image reference")
    encoded = json.dumps(ref)
    for number, line in enumerate(text.splitlines(), start=1):
        if re.search(r'"image"\s*:\s*' + re.escape(encoded), line):
            return [Pin(rel, number, "image", ref)]
    raise PinError(f"{rel}: the image must be written on the line of its key")


def _bom_pins(root: Path, path: Path) -> list[Pin]:
    """The images of a bill of materials, located without trusting it: the check reads
    names, tags and digests only; the start check verifies the signature."""
    text = _read(path)
    rel = _rel(root, path)
    try:
        node = yaml.compose(text)
    except yaml.YAMLError as exc:
        raise PinError(f"{rel}: not YAML ({type(exc).__name__})") from exc
    found: list[Pin] = []
    for key, repos in _mapping_items(node):
        if key.value != "repos" or not isinstance(repos, yaml.SequenceNode):
            continue
        for r_index, repo in enumerate(repos.value):
            for rkey, entries in _mapping_items(repo):
                if rkey.value != "images" or not isinstance(entries, yaml.SequenceNode):
                    continue
                for i_index, entry in enumerate(entries.value):
                    fields = {k.value: v for k, v in _mapping_items(entry)}
                    parts = [fields.get(name) for name in ("name", "tag", "digest")]
                    if not all(isinstance(part, yaml.ScalarNode) for part in parts):
                        raise PinError(f"{rel}:{entry.start_mark.line + 1}: repos[{r_index}]"
                                       f".images[{i_index}] needs name, tag and digest")
                    name, tag, digest = (part.value for part in parts)
                    found.append(Pin(rel, parts[2].start_mark.line + 1,
                                     f"repos[{r_index}].images[{i_index}]",
                                     f"{name}:{tag}@{digest}"))
    return found


def _sources(root: Path) -> tuple[list[Path], list[Path]]:
    src = root / "src"
    compose = sorted(src.rglob("docker-compose*.yml"))
    service_env = sorted(src.rglob(SERVICE_ENV_NAME))
    return compose, service_env


def collect(repo_root: Path) -> list[Pin]:
    """Every pin of the checkout, in a stable order."""
    root = Path(repo_root)
    compose, service_env = _sources(root)
    pins: list[Pin] = []
    for path in compose:
        pins += _compose_pins(root, path)
    for path in service_env:
        pins += _service_env_pins(root, path)
    bom = images.bom_path(root, images.core_version(root))
    if bom.is_file():
        pins += _bom_pins(root, bom)
    if len(pins) > MAX_PINS:
        raise PinError(f"more than {MAX_PINS} pins")
    return pins


# ── resolving them ───────────────────────────────────────────────────────────


def on_release_tag(repo_root: Path, env: dict[str, str] | None = None) -> str | None:
    """The release tag the run is on, or None: a CI ref of a tag, or a `v<X.Y.Z>` tag on
    the checked-out commit."""
    env = os.environ if env is None else env
    if env.get("GITHUB_REF_TYPE") == "tag" or env.get("GITHUB_REF", "").startswith(
        "refs/tags/"
    ):
        return env.get("GITHUB_REF_NAME") or env.get("GITHUB_REF", "")
    try:
        done = subprocess.run(
            ["git", "-C", str(repo_root), "tag", "--points-at", "HEAD"],
            capture_output=True, text=True, timeout=30, check=False,
        )
    except (OSError, subprocess.SubprocessError):
        return None  # no git (a release tarball): nothing to compare
    for tag in done.stdout.split() if done.returncode == 0 else []:
        if _RELEASE_TAG_RE.match(tag):
            return tag
    return None


def _candidate_registry(value: str) -> str:
    prefix = images.validate_mirror(value)
    if not prefix:
        raise PinError("candidate mode needs --registry=<host:port>/<path>/ of the test registry")
    host = prefix.split("/", 1)[0]
    if not own_images._loopback_registry(host):
        raise PinError(f"--registry {prefix}: the candidate registry must be on the loopback "
                       "interface (a local test registry)")
    return prefix


def _ask(registry, ref: images.Ref) -> tuple[str | None, str | None, str | None]:
    """(digest problem, tag problem, transport problem) of `ref` at the registry it names.
    A problem is None when that part holds."""
    try:
        registry.resolve(ref.registry, ref.repository, ref.digest)
    except images.NotFound:
        return "unknown digest", None, None
    except images.Unreachable as exc:
        return None, None, f"registry not reachable ({exc})"
    except images.ImageError as exc:
        return None, None, f"registry refused ({exc})"
    if ref.tag is None:
        return None, None, None
    try:
        served = registry.resolve(ref.registry, ref.repository, ref.tag)
    except images.NotFound:
        return None, f"tag {ref.tag} does not exist", None
    except images.Unreachable as exc:
        return None, None, f"registry not reachable ({exc})"
    except images.ImageError as exc:
        return None, None, f"registry refused ({exc})"
    if served != ref.digest:
        return None, f"tag {ref.tag} points to {served}, not to the pinned digest", None
    return None, None, None


def _problem(registry, ref: images.Ref) -> str | None:
    digest, tag, transport = _ask(registry, ref)
    return digest or tag or transport


def _behind(prefix: str, text: str) -> images.Ref:
    """The pin as a mirror serves it: the reference as written, behind the prefix (as
    `PAPAIA_IMAGE_MIRROR` places every image, images.mirrored)."""
    return images.parse_ref(prefix + text)


def _own_builds(repo_root: Path, path: Path) -> tuple[str, dict[str, dict]]:
    prefix, entries = own_images.read_builds(path)
    declared = {image.name for image in own_images.load(repo_root)}
    built = {entry["name"]: entry for entry in entries}
    missing = sorted(declared - set(built))
    if missing:
        raise PinError(f"--own-builds: not built: {', '.join(missing)}")
    if not prefix:
        raise PinError("--own-builds: the build went to the release registry; check it "
                       "without --own-builds")
    return prefix, built


def check(
    repo_root: Path,
    *,
    mode: str,
    registry,
    candidate_registry: str = "",
    own_builds: Path | None = None,
    env: dict[str, str] | None = None,
) -> tuple[list[Pin], list[Finding]]:
    """(pins, findings) of the checkout; no findings means every pin resolves."""
    root = Path(repo_root)
    if mode not in MODES:
        raise PinError(f"mode must be one of {', '.join(MODES)}")
    prefix = ""
    if mode == "candidate":
        tag = on_release_tag(root, env)
        if tag:
            raise PinError(f"candidate mode refuses to run on the release tag {tag}: a "
                           "release is checked in release mode against the release registry")
        prefix = _candidate_registry(candidate_registry)
    elif candidate_registry:
        raise PinError("--registry is for candidate mode only")
    if own_builds is not None and mode != "release":
        raise PinError("--own-builds is for release mode only")
    own_prefix, built = _own_builds(root, own_builds) if own_builds is not None else ("", {})

    pins = collect(root)
    exceptions = images.load_exceptions(root)
    findings: list[Finding] = []
    answers: dict[str, str | None] = {}
    for pin in pins:
        why = images.pin_problem(pin.ref, exceptions)
        if why is not None:
            findings.append(Finding(pin, f"not pinned: {why}"))
            continue
        ref = images.parse_ref(pin.ref)
        if mode == "release" and own_images._loopback_registry(ref.registry):
            findings.append(Finding(pin, "names a loopback test registry; a release pins "
                                         "the published image"))
            continue
        if pin.ref not in answers:
            answers[pin.ref] = _resolve(pin.ref, ref, registry, mode, prefix, own_prefix,
                                        built)
        if answers[pin.ref] is not None:
            findings.append(Finding(pin, answers[pin.ref]))
    return pins, findings


def _resolve(text: str, ref: images.Ref, registry, mode: str, prefix: str,
             own_prefix: str, built: dict[str, dict]) -> str | None:
    name = f"{ref.registry}/{ref.repository}"
    if name in built:
        entry = built[name]
        if (entry["tag"], entry["digest"]) != (ref.tag, ref.digest):
            return (f"the build of this release is {entry['tag']}@{entry['digest']}; rebuild "
                    "and pin (build-images pin)")
        local = _problem(registry, _behind(own_prefix, text))
        return None if local is None else f"{local} in the build registry {own_prefix}"
    if mode == "candidate":
        local_digest, local_tag, transport = _ask(registry, _behind(prefix, text))
        if transport is not None:
            return f"{transport} at the candidate registry {prefix}"
        if local_tag is not None and local_digest is None:
            return f"{local_tag} (candidate registry {prefix})"
        if local_digest is None:
            return None
        upstream = _problem(registry, ref)
        if upstream == "unknown digest":
            return (f"unknown digest: neither the candidate registry {prefix} nor "
                    f"{ref.registry} has it")
        return upstream
    return _problem(registry, ref)


# ── re-pinning ───────────────────────────────────────────────────────────────


def _same_image(a: images.Ref, b: images.Ref) -> bool:
    return (a.registry, a.repository) == (b.registry, b.repository)


def repin(repo_root: Path, new: str) -> list[str]:
    """Write `new` (`name:tag@sha256:<digest>`) into every compose and service-env pin of
    the same image; the locations changed. The bill of materials is not touched."""
    root = Path(repo_root)
    why = images.pin_problem(new)
    if why is not None:
        raise PinError(f"{new[:200]}: {why}")
    target = images.parse_ref(new)
    if own_images._loopback_registry(target.registry):
        raise PinError("a pin names the published image, never a loopback test registry")
    own = {image.name for image in own_images.load(root)}
    if f"{target.registry}/{target.repository}" in own:
        version = images.core_version(root)
        if target.tag != version:
            raise PinError(f"an own image of the core is pinned with the core version "
                           f"{version}; use build-images pin")
    compose, service_env = _sources(root)
    plan: dict[Path, list[Pin]] = {}
    for path in compose:
        plan[path] = _compose_pins(root, path)
    for path in service_env:
        plan[path] = _service_env_pins(root, path)
    changed: list[str] = []
    for path, pins in plan.items():
        hits = [pin for pin in pins if _matches(pin.ref, target)]
        if not hits:
            continue
        lines = _read(path).splitlines(keepends=True)
        for pin in hits:
            if pin.ref == new:
                continue
            line = lines[pin.line - 1]
            if line.count(pin.ref) != 1:
                raise PinError(f"{pin.location}: the pin must stand once on its line")
            lines[pin.line - 1] = line.replace(pin.ref, new)
            changed.append(f"{pin.location}: {pin.where}")
        path.write_text("".join(lines), encoding="utf-8")
    if not changed and not any(_matches(pin.ref, target) for pins in plan.values()
                               for pin in pins):
        raise PinError(f"{target.registry}/{target.repository} is pinned nowhere in compose "
                       "or service-env.json")
    return changed


def _matches(text: str, target: images.Ref) -> bool:
    try:
        return _same_image(images.parse_ref(text), target)
    except images.ImageError:
        return False


# ── command line ─────────────────────────────────────────────────────────────


def main(argv: list[str] | None = None, *, registry=None) -> int:
    parser = argparse.ArgumentParser(prog="check-image-pins",
                                     description=__doc__.split("\n")[0])
    parser.add_argument("--repo-root", default=str(Path(__file__).resolve().parents[2]))
    sub = parser.add_subparsers(dest="action", required=True)
    p_check = sub.add_parser("check", help="resolve every pin against the registry")
    p_check.add_argument("--mode", choices=MODES, required=True)
    p_check.add_argument("--registry", default="",
                         help="candidate mode: loopback test registry prefix ending in '/'")
    p_check.add_argument("--own-builds", default=None,
                         help="release mode: builds file of tools/build-images for the "
                              "own images")
    sub.add_parser("list", help="print every pin with file and line")
    p_repin = sub.add_parser("repin", help="move every pin of one image")
    p_repin.add_argument("--ref", action="append", required=True,
                         help="name:tag@sha256:<digest> (repeatable)")
    args = parser.parse_args(argv)
    root = Path(args.repo_root)
    try:
        if args.action == "list":
            for pin in collect(root):
                print(f"{pin.location}: {pin.where}: {pin.ref}")
            return 0
        if args.action == "repin":
            for ref in args.ref:
                for location in repin(root, ref):
                    print(f"pinned {location}")
                    if SERVICE_ENV_NAME in location:
                        print(f"  {location.split(':', 1)[0]} also names the source commit "
                              "of the image: regenerate it from the released source "
                              "(python -m lib.me_profile generate)")
            print("The signed bill of materials is regenerated by the release; run "
                  "check-image-pins check again.")
            return 0
        pins, findings = check(
            root, mode=args.mode, registry=registry or images.Registry(),
            candidate_registry=args.registry,
            own_builds=Path(args.own_builds) if args.own_builds else None,
        )
    except (PinError, images.ImageError, own_images.OwnImageError, OSError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2
    for finding in findings:
        print(f"ERROR: {finding}", file=sys.stderr)
    where = f", candidate registry {args.registry}" if args.mode == "candidate" else ""
    if findings:
        print(f"{len(findings)} of {len(pins)} pin(s) do not resolve ({args.mode} mode{where}).",
              file=sys.stderr)
        return 1
    print(f"{len(pins)} pin(s) resolve: every digest exists and every tag points to it "
          f"({args.mode} mode{where}).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
