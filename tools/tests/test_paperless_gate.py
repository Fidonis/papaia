"""The proxy side of the Paperless gate (PLT-22): the proxy clears the identity header
and the gate header on every host, sets its own gate secret only on the Paperless route,
and keeps the chat service off the Paperless network.

The secret is the proxy's own (the MCP server has another one), generated by `setup`,
stored as a file outside every `.env` and rotated with `papaia-ctl secrets rotate`."""

