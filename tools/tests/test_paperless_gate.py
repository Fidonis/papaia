# ── networks: the chat service is not on the Paperless network ───────────────


def _paperless_stack(tmp_path: Path, attach: list[str]) -> tuple[Path, Path, dict]:
    repo_root = REAL_REPO
    config_dir = tmp_path / "config"
    addon = tmp_path / "paperless"
    addon.mkdir()
    (addon / "docker-compose.yml").write_text(
        yaml.safe_dump(
            {
                "services": {
                    "paperless": {"image": "x", "networks": ["papaia-paperless-net"]},
                    "paperless-mcp": {"image": "y", "networks": ["papaia-paperless-net"]},
                },
                "networks": {
                    "papaia-paperless-net": {"name": "${PAPAIA_PROJECT:-papaia}-paperless-net"}
                },
            }
        ),
        encoding="utf-8",
    )
    manifest = {
        "name": "paperless",
        "version": "2.0.0",
        "networks": {"app_network": "${PAPAIA_PROJECT:-papaia}-paperless-net", "attach": attach},
    }
    (addon / "papaia-app.yaml").write_text(yaml.safe_dump(manifest), encoding="utf-8")
    common.ensure_dir(config_dir / "overrides" / "addons")
    (config_dir / ".env").write_text("PAPAIA_PROJECT=papaia-dev\n", encoding="utf-8")
    (config_dir / "deployment.yaml").write_text(
        yaml.safe_dump({"addons": [{"name": "paperless", "path": str(addon), "active": True}]}),
        encoding="utf-8",
    )
    return repo_root, config_dir, manifest


def test_the_chat_service_joins_the_front_network_not_the_paperless_network(tmp_path):
    repo_root, config_dir, manifest = _paperless_stack(
        tmp_path, ["nginx-proxy-manager", "librechat"]
    )

    gen_override.generate_overrides(config_dir, repo_root)
    gen_override.generate_addon_join_overrides(config_dir, repo_root)

    core = yaml.safe_load(
        (config_dir / "overrides" / "docker-compose.paperless.override.yml").read_text(
            encoding="utf-8"
        )
    )
    assert core["services"] == {
        "nginx-proxy-manager": {"networks": ["papaia-dev-paperless-net"]},
        "librechat": {"networks": ["papaia-dev-paperless-front"]},
    }
    assert core["networks"] == {
        "papaia-dev-paperless-net": {"external": True},
        "papaia-dev-paperless-front": {"external": True},
    }
    addon = yaml.safe_load(
        (
            config_dir / "overrides" / "addons" / "docker-compose.paperless-front.override.yml"
        ).read_text(encoding="utf-8")
    )
    assert addon == {
        "services": {"paperless-mcp": {"networks": ["papaia-paperless-net", "paperless-front"]}},
        "networks": {"paperless-front": {"name": "papaia-dev-paperless-front"}},
    }


