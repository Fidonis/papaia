def test_the_proxy_secret_is_its_own_and_not_the_mcp_servers(config_dir):
    """The MCP server's secret lives with the add-on; the proxy's directory holds only
    the proxy's, so revoking one never touches the other."""
    paperless_gate.ensure_proxy_secret(config_dir)

    directory = config_dir / paperless_gate.PROXY_SECRET_DIR
    assert directory.name == "proxy"
    assert sorted(p.name for p in directory.iterdir()) == sorted(
        [paperless_gate.SECRET_FILE, paperless_gate.NGINX_INCLUDE]
    )
    assert paperless_gate.ROTATE_TARGETS == ("paperless-gate/proxy",)


def test_creating_the_secret_writes_one_audit_row_without_the_value(config_dir):
    paperless_gate.ensure_proxy_secret(
        config_dir, correlation="0" * 8 + "-0000-4000-8000-" + "0" * 12
    )
    secret = paperless_gate.read_proxy_secret(config_dir)

    rows = _audit_rows(config_dir)
    assert len(rows) == 1
    row = rows[0]
    assert row["format"] == "papaia.audit/1"
    assert row["event"] == "paperless_gate_secret_created"
    assert row["effect"] == "write"
    assert row["correlation_id"] == "00000000-0000-4000-8000-000000000000"
    assert row["detail"] == {"target": "paperless-gate/proxy"}
    assert secret not in json.dumps(rows)

    paperless_gate.ensure_proxy_secret(config_dir)
    assert len(_audit_rows(config_dir)) == 1  # nothing written, nothing audited


def _audit_rows(config_dir: Path) -> list[dict]:
    path = config_dir / "audit" / "papaia-ctl.jsonl"
    if not path.is_file():
        return []
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line]


# ── rotation ─────────────────────────────────────────────────────────────────


def test_rotation_replaces_the_secret_in_both_files_and_is_audited(config_dir):
    paperless_gate.ensure_proxy_secret(config_dir)
    old = paperless_gate.read_proxy_secret(config_dir)

    paperless_gate.rotate(config_dir, "paperless-gate/proxy")

    new = paperless_gate.read_proxy_secret(config_dir)
    include = config_dir / paperless_gate.PROXY_SECRET_DIR / paperless_gate.NGINX_INCLUDE
    assert new != old
    assert SAFE_SECRET.match(new)
    assert new in include.read_text(encoding="utf-8")
    assert old not in include.read_text(encoding="utf-8")
    rows = _audit_rows(config_dir)
    assert [r["event"] for r in rows] == [
        "paperless_gate_secret_created",
        "paperless_gate_secret_rotated",
    ]
    assert old not in json.dumps(rows) and new not in json.dumps(rows)


