def _paperless(config_dir: Path, url: str, *, active: bool = True) -> None:
    common.ensure_dir(config_dir / "addons" / "paperless")
    (config_dir / "addons" / "paperless" / ".env").write_text(
        f"PAPERLESS_PUBLIC_URL={url}\n", encoding="utf-8"
    )
    (config_dir / "deployment.yaml").write_text(
        yaml.safe_dump(
            {"addons": [{"name": "paperless", "path": "/x/paperless", "active": active}]}
        ),
        encoding="utf-8",
    )


class _FakeNpm:
    def __init__(self, hosts: list[dict] | None = None, strip_changes=(False,)) -> None:
        self.hosts = hosts or []
        self.strip_changes = list(strip_changes)
        self.created: list[dict] = []
        self.updated: list[tuple[int, dict]] = []
        self.reloads = 0

    def install(self, monkeypatch) -> None:
        monkeypatch.setattr(npm_provision, "_wait_for_npm", lambda base_url, timeout=60: None)
        monkeypatch.setattr(npm_provision, "_get_token", lambda base_url, email, password: "t")
        monkeypatch.setattr(
            npm_provision,
            "_existing_domains",
            lambda base_url, token: {d for h in self.hosts for d in h["domain_names"]},
        )
        monkeypatch.setattr(npm_provision, "_create_proxy_host", lambda *a, **k: None)
        monkeypatch.setattr(npm_provision, "_list_proxy_hosts", lambda base_url, token: self.hosts)
        monkeypatch.setattr(
            npm_provision,
            "_post_proxy_host",
            lambda base_url, token, body: self.created.append(body),
        )
        monkeypatch.setattr(
            npm_provision,
            "_put_proxy_host",
            lambda base_url, token, host_id, body: self.updated.append((host_id, body)),
        )
        monkeypatch.setattr(
            paperless_gate,
            "reload_proxy",
            lambda project: setattr(self, "reloads", self.reloads + 1) or True,
        )
        # The app-origin guard has its own tests (test_edge_guard.py).
        monkeypatch.setattr(edge_guard, "install", lambda project, bases: False)
        monkeypatch.setattr(
            paperless_gate,
            "install_strip_file",
            lambda project, extra="": (
                self.strip_changes.pop(0) if len(self.strip_changes) > 1 else self.strip_changes[0]
            ),
        )


def test_the_paperless_route_forwards_to_the_gate_with_the_secret_include(config_dir, monkeypatch):
    paperless_gate.ensure_proxy_secret(config_dir)
    _paperless(config_dir, "https://docs.papaia.example.com")
    npm = _FakeNpm()
    npm.install(monkeypatch)

    assert npm_provision.provision_npm_hosts(_nginx_tree(), config_dir) is True

    assert len(npm.created) == 1
    body = npm.created[0]
    assert body["domain_names"] == ["docs.papaia.example.com"]
    assert (body["forward_scheme"], body["forward_host"], body["forward_port"]) == (
        "http",
        "paperless",
        8001,
    )
    assert body["advanced_config"] == paperless_gate.route_advanced_config()
    assert paperless_gate.read_proxy_secret(config_dir) not in json.dumps(body)


