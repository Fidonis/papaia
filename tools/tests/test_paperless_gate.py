def test_every_proxy_host_clears_both_headers():
    conf = paperless_gate.strip_config()

    assert 'more_clear_input_headers "X-Papaia-Remote-User" "X-Papaia-Gate";' in conf


def test_the_strip_file_keeps_what_the_operator_wrote():
    operator = "# operator\nadd_header X-Operator yes;\n"

    merged = paperless_gate.merge_strip(operator)

    assert merged == paperless_gate.strip_config() + operator
    assert paperless_gate.merge_strip(merged) == merged
    assert paperless_gate.merge_strip("") == paperless_gate.strip_config()


def test_hosts_created_by_provisioning_clear_both_headers_themselves():
    body = npm_provision.proxy_host_body("chat.example.com", "librechat", 3080, "http")

    assert body["advanced_config"] == paperless_gate.strip_config()
    unverified = npm_provision.proxy_host_body(
        "auth.example.com", "keycloak", 8443, "https", ssl_verify=False
    )
    assert (
        unverified["advanced_config"] == paperless_gate.strip_config() + "proxy_ssl_verify off;\n"
    )


def test_the_paperless_route_sets_the_secret_from_the_file_only():
    conf = paperless_gate.route_advanced_config()

    assert conf.startswith("location / {")
    assert 'more_clear_input_headers "X-Papaia-Remote-User";' in conf
    assert f"include {paperless_gate.PROXY_MOUNT}/{paperless_gate.NGINX_INCLUDE};" in conf
    assert "include conf.d/include/proxy.conf;" in conf
    # The header is never set with proxy_set_header: at server level the proxy
    # manager's own location ignores it, and the value would sit in its database.
    assert "proxy_set_header X-Papaia" not in conf
    assert "X-Papaia-Gate:" not in conf


def test_the_proxy_mounts_the_secret_directory_read_only():
    compose = yaml.safe_load(
        (REAL_REPO / "src" / "infra" / "nginx" / "docker-compose.yml").read_text(encoding="utf-8")
    )
    volumes = compose["services"]["nginx-proxy-manager"]["volumes"]
    mounts = [
        v for v in volumes if isinstance(v, dict) and v.get("target") == paperless_gate.PROXY_MOUNT
    ]

    assert mounts == [
        {
            "type": "bind",
            "source": "${PAPAIA_CONFIG_DIR}/" + paperless_gate.PROXY_SECRET_DIR,
            "target": paperless_gate.PROXY_MOUNT,
            "read_only": True,
            "bind": {"create_host_path": False},
        }
    ]
    # No other service of the core sees the proxy's secret.
    for path in (REAL_REPO / "src").rglob("docker-compose.yml"):
        text = path.read_text(encoding="utf-8")
        if path != REAL_REPO / "src" / "infra" / "nginx" / "docker-compose.yml":
            assert "paperless-gate" not in text, path


